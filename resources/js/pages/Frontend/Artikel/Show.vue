<h2 class="text-2xl font-bold text-slate-900 dark:text-white mt-10 mb-4">1. Honen-in Temple</h2>
<p>Located just off the Philosopher's Path, Honen-in is often overlooked. Its thatched gate and sand mounds, which are raked into seasonal designs, create an atmosphere of profound tranquility. In autumn, the maples here create a canopy of deep reds that reflect beautifully in the small pond.</p>
