<h2 class="text-2xl font-bold text-slate-900 dark:text-white mt-10 mb-4">2. Otagi Nenbutsu-ji</h2>
<p>Tucked away in the far reaches of Arashiyama, this temple is home to over 1,200 whimsical stone figures (rakan). Each one was carved by a different person, giving them unique, often humorous expressions. It’s one of the most charming and least visited sites in the area.</p>
<p>The journey to Otagi Nenbutsu-ji is as beautiful as the destination itself, winding through the traditional preserved street of Saga-Toriimoto. It's a perfect escape for those looking to experience the spiritual side of Japan without the crowds.</p>
